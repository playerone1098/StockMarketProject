import React, { useState } from 'react';
import { Helmet } from 'react-helmet-async';

export const FAQ = () => {
  const [searchQuery, setSearchQuery] = useState('');
  const [activeCategory, setActiveCategory] = useState('all');
  const [openIndex, setOpenIndex] = useState(null);

  const categories = [
    { id: 'all', name: 'All Questions' },
    { id: 'trading', name: 'Trading Ideas' },
    { id: 'ipos', name: 'IPO Board' },
    { id: 'data', name: 'Market Data & Accuracy' }
  ];

  const faqs = [
    {
      category: 'trading',
      question: 'What are Trading Ideas on StockVista?',
      answer: 'Trading Ideas are research-backed stock recommendations generated by our technical and fundamental analysis desk. Each idea has designated parameters: Entry Price (buying threshold), Target Price (expected selling level), and Stop Loss (level to cut losses). We cover Intraday, Short-term, Medium-term, and Long-term timelines.'
    },
    {
      category: 'trading',
      question: 'Are StockVista Trading Ideas financial advice?',
      answer: 'No. The trading ideas, stock screeners, and commentary on StockVista are strictly for educational and informational purposes. Investing in capital markets carries high risk. You must perform your own due diligence or consult a registered investment advisor before committing capital.'
    },
    {
      category: 'ipos',
      question: 'How often is the IPO Tracker updated?',
      answer: 'Our IPO board is updated continuously as companies file draft prospects (DRHP) with SEBI. timeline dates (Open, Close, Listing) and subscription statistics (retail, NII, QIB multiples) are monitored and updated daily during listing phases.'
    },
    {
      category: 'ipos',
      question: 'What do the different IPO statuses mean?',
      answer: 'We classify IPOs into 4 statuses: "Upcoming" (SEBI approved but dates not yet set), "Open" (currently bidding/subscribing), "Closed" (bidding completed, awaiting listing), and "Listed" (successfully trading on stock exchanges like NSE/BSE).'
    },
    {
      category: 'data',
      question: 'Where does StockVista get its stock prices?',
      answer: 'StockVista utilizes a consolidated local reference directory matching historical Indian stock performance. Ticker prices are refreshed periodically to ensure accurate data matching for indicators and screeners.'
    },
    {
      category: 'data',
      question: 'How do you calculate percentage price changes?',
      answer: 'The price change and change percentage are calculated based on the day change against the previous session close price: (Day Change / (Current Price - Day Change)) * 100.'
    }
  ];

  const toggleFAQ = (index) => {
    if (openIndex === index) {
      setOpenIndex(null);
    } else {
      setOpenIndex(index);
    }
  };

  const filteredFaqs = faqs.filter(faq => {
    const matchesSearch = faq.question.toLowerCase().includes(searchQuery.toLowerCase()) || 
                          faq.answer.toLowerCase().includes(searchQuery.toLowerCase());
    const matchesCategory = activeCategory === 'all' || faq.category === activeCategory;
    return matchesSearch && matchesCategory;
  });

  return (
    <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      <Helmet>
        <title>Frequently Asked Questions (FAQ) | StockVista Help</title>
        <meta name="description" content="Find answers to common questions about StockVista's trading ideas, stop loss criteria, IPO board, subscription updates, and market data sources." />
      </Helmet>

      {/* Header */}
      <div className="text-center mb-12">
        <h1 className="text-4xl font-black text-navy-950 mb-4 tracking-tight">
          Frequently Asked Questions
        </h1>
        <p className="text-sm text-gray-500 max-w-2xl mx-auto font-medium">
          Have questions about our trading signals, IPO lists, or data accuracy? Find answers below.
        </p>
      </div>

      {/* Search and Filters */}
      <div className="mb-10 space-y-6">
        <div className="relative">
          <span className="absolute inset-y-0 left-0 flex items-center pl-3 pointer-events-none text-gray-400">
            🔍
          </span>
          <input
            type="text"
            placeholder="Search FAQs (e.g. stop loss, target, IPO)..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="w-full pl-9 pr-4 py-3.5 border border-gray-250 rounded-2xl focus:outline-none focus:ring-1 focus:ring-brand-500 focus:border-brand-500 transition shadow-sm text-sm text-navy-950"
          />
        </div>

        {/* Category Pill Filters */}
        <div className="flex flex-wrap gap-2 justify-center">
          {categories.map((cat) => (
            <button
              key={cat.id}
              onClick={() => { setActiveCategory(cat.id); setOpenIndex(null); }}
              className={`px-5 py-2.5 rounded-full text-xs font-bold transition-all ${
                activeCategory === cat.id
                  ? 'bg-brand-500 text-white shadow-md shadow-brand-500/10'
                  : 'bg-white text-navy-800 border border-gray-250 hover:bg-navy-50'
              }`}
            >
              {cat.name}
            </button>
          ))}
        </div>
      </div>

      {/* Accordion Questions List */}
      <div className="space-y-4">
        {filteredFaqs.length > 0 ? (
          filteredFaqs.map((faq, index) => {
            const isOpen = openIndex === index;
            return (
              <div
                key={index}
                className="bg-white rounded-2xl border border-gray-100 shadow-sm overflow-hidden transition duration-300"
              >
                <button
                  onClick={() => toggleFAQ(index)}
                  className="w-full px-6 py-5 text-left flex justify-between items-center hover:bg-gray-50 transition focus:outline-none"
                >
                  <span className="font-extrabold text-navy-950 text-base md:text-lg">{faq.question}</span>
                  <span className={`w-8 h-8 rounded-full bg-brand-50 flex items-center justify-center text-brand-600 transform transition-transform duration-300 ${isOpen ? 'rotate-180' : ''}`}>
                    ▼
                  </span>
                </button>
                
                {/* Accordion body panel */}
                <div
                  className={`px-6 transition-all duration-300 ease-in-out overflow-hidden ${
                    isOpen ? 'max-h-96 py-5 border-t border-gray-100' : 'max-h-0'
                  }`}
                >
                  <p className="text-gray-600 leading-relaxed text-xs md:text-sm">
                    {faq.answer}
                  </p>
                </div>
              </div>
            );
          })
        ) : (
          <div className="text-center py-12 bg-white rounded-2xl border border-gray-150 shadow-sm">
            <h3 className="font-extrabold text-navy-950 text-base mb-1">No FAQs Found</h3>
            <p className="text-gray-500 text-xs">
              We couldn't find any questions matching "{searchQuery}". Try using different terms.
            </p>
          </div>
        )}
      </div>
    </div>
  );
};
